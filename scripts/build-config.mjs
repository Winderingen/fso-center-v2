import { writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import { API_VERSION } from '../supabase/functions/_shared/domain.mjs';
export function productionConfig(env) {
  const ref=(env.SUPABASE_PROJECT_REF||'').trim(), key=(env.SUPABASE_PUBLISHABLE_KEY||'').trim();
  if(!/^[a-z0-9]{20}$/.test(ref)) throw new Error('Set the new SUPABASE_PROJECT_REF repository variable (20-character project ref).');
  if(key.startsWith('sb_secret_')) throw new Error('Secret keys must never be included in the website. Use a publishable/anon key.');
  if(!key.startsWith('sb_publishable_')) {
    let payload;try{payload=JSON.parse(Buffer.from(key.split('.')[1]||'','base64url').toString());}catch{}
    if(payload?.role!=='anon') throw new Error('Set SUPABASE_PUBLISHABLE_KEY to a publishable key or legacy anon JWT; service_role is not allowed.');
  }
  return {mode:'supabase',supabaseUrl:`https://${ref}.supabase.co`,publishableKey:key,expectedApiVersion:API_VERSION};
}
if(process.argv[1] && fileURLToPath(import.meta.url) === path.resolve(process.argv[1])) {
  await writeFile('site/config.js',`// Generated by GitHub Actions; public settings only.\nwindow.FSO_CONFIG = ${JSON.stringify(productionConfig(process.env),null,2)};\n`);
  console.log(`Public website config generated; expected API ${API_VERSION}.`);
}
